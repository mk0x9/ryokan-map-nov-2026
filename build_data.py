# Build map/data.js (window.RYOKANS = [...]) from work/build_sheet.build() rows + work/data/coords.json.
# Run: python3 map/build_data.py
# Starred properties (work/data/starred.json) get "starred": true; their plans include over-budget ones, all kept.
import contextlib, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = f"{ROOT}/work"
sys.path.insert(0, WORK)
import build_sheet as bs  # noqa: E402

BUDGET = 60000
RANGES = {"16-18": ("16", "17"), "17-19": ("17", "18"), "16-19": ("16", "17", "18")}
SKIP = {"", "unknown", "not stated"}
IMG_BASE = "https://cdn.jalan.jp/jalan/images/"  # stripped from photo URLs to keep data.js small


def ident(v):
    return str(v or "").lstrip("'")


def img(v):
    m = re.match(r'=IMAGE\("([^"]+)"\)', v or "")
    if not m:
        return None
    u = m.group(1)
    return u[len(IMG_BASE):] if u.startswith(IMG_BASE) else u


def trim(v, n=300):
    v = re.sub(r"\s+", " ", str(v or "")).strip()
    return v if len(v) <= n else v[:n - 1].rstrip() + "…"


def avgs(nightly):
    out = {}
    for k, nights in RANGES.items():
        vals = [nightly.get(n) for n in nights]
        out[k] = round(sum(vals) / len(vals)) if all(isinstance(x, (int, float)) for x in vals) else None
    return out


def compact(d):
    return {k: v for k, v in d.items() if v not in (None, "", [], {}) and not (isinstance(v, str) and v in SKIP)}


def main():
    with contextlib.redirect_stdout(io.StringIO()):
        r_rows, p_rows = bs.build()
    RH, PH = bs.RYOKAN_HEADERS, bs.PLAN_HEADERS
    coords = json.load(open(f"{WORK}/data/coords.json")) if os.path.exists(f"{WORK}/data/coords.json") else {}
    starred_ids = set(json.load(open(f"{WORK}/data/starred.json"))["ids"]) if os.path.exists(f"{WORK}/data/starred.json") else set()

    plans = {}
    for row in p_rows:
        p = dict(zip(PH, row))
        nightly = {"16": p["Nov 16 (¥)"], "17": p["Nov 17 (¥)"], "18": p["Nov 18 (¥)"]}
        plans.setdefault(ident(p["Jalan ID"]), []).append(compact({
            "name": trim(p["Plan"], 160), "meals": p["Meals"], "dinnerStyle": p["Dinner style"],
            "dinner": trim(p["Dinner"]), "room": trim(p["Room"]), "roomStyle": p["Room style"],
            "bedding": p["Bedding"], "size": p["Size"], "view": p["View"], "balcony": p["Balcony"],
            "bath": p["In-room bath"], "photo": img(p["Room photo"]),
            "prices": [nightly["16"], nightly["17"], nightly["18"]],
            "cancel": p["Free cancellation until"], "oneNight": p["1-night limit"] == "Yes" or None,
            "planCd": ident(p["Plan code"]), "roomCd": ident(p["Room code"]),
        }))
        plans[ident(p["Jalan ID"])][-1]["_avg"] = list(avgs(nightly).values())  # build-time only

    out, no_coords = [], []
    for row in r_rows:
        r = dict(zip(RH, row))
        rid = ident(r["Jalan ID"])
        ps = plans.get(rid, [])

        def cheapest(i, meals=None):
            vals = [p["_avg"][i] for p in ps if p["_avg"][i] is not None and p["_avg"][i] <= BUDGET
                    and (meals is None or p.get("meals") == meals)]
            return min(vals) if vals else None

        c = coords.get(rid)
        if not c:
            no_coords.append(rid)
        two = [cheapest(i, "Breakfast & dinner") for i in range(3)]
        two = [v for v in two if v is not None]
        out.append(compact({
            "id": rid, "starred": r.get("Starred") == "★" or rid in starred_ids or None, "name": r["Ryokan"], "nameJp": r["Name (Japanese)"], "pref": r["Prefecture"],
            "area": r["Area (Jalan)"], "setting": r["Setting"], "settingNote": trim(r["Setting note"]),
            "lat": c[0] if c else None, "lng": c[1] if c else None,
            "photos": compact({k: img(r[h]) for k, h in
                               [("main", "Photo"), ("bath", "Bath photo"), ("room", "Room photo"), ("food", "Food photo")]}),
            "rating": r["Rating"], "reviews": r["Reviews"],
            "scores": compact({k: r[h] for k, h in [("room", "Room"), ("bath", "Bath"), ("breakfast", "Breakfast"),
                                                    ("dinner", "Dinner"), ("service", "Service"), ("clean", "Cleanliness")]}),
            "onsen": trim(r["Onsen"]), "baths": trim(r["Baths"]),
            "strong": [trim(s, 200) for s in (r["Strong points"] or "").split(" • ") if s.strip()],
            "watch": trim(r["Watch-outs"]), "summary": trim(r["Review summary"]),
            "cheapest": [cheapest(i) for i in range(3)], "cheapest2": min(two) if two else None,
            "checkInOut": r["Check-in / out"],
            "plans": [{k: v for k, v in p.items() if k != "_avg"}
                      for p in sorted(ps, key=lambda p: min([v for v in p["_avg"] if v is not None] or [9e9]))],
        }))

    js = "// Generated by map/build_data.py; do not edit.\n" + \
         f"window.IMG_BASE = {json.dumps(IMG_BASE)};\nwindow.RYOKANS = " + \
         json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(f"{ROOT}/map/data.js", "w").write(js)
    print(json.dumps({"ryokans": len(out), "with_coords": len(out) - len(no_coords), "no_coords": no_coords,
                      "plans": sum(len(v) for v in plans.values()), "bytes": len(js.encode())}))


if __name__ == "__main__":
    main()
